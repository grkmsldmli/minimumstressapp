import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Concatenates supabase/migrations/ into the single file you paste into the
 * SQL editor.
 *
 * Written after apply.sql drifted from the migrations it claims to be
 * generated from — which is the one failure mode that matters here, because
 * the drift is invisible until a column is missing in production and present
 * in every test.
 */

const MIGRATIONS = join(process.cwd(), "supabase", "migrations");
const OUT = join(process.cwd(), "supabase", "apply.sql");

const HEADER = `-- Minimum Stress — full schema, generated from supabase/migrations/
--
-- Generated by scripts/build-apply-sql.mjs — edit the migrations, not this.
--
-- Safe to run more than once. Every statement is guarded, so pasting this
-- into a project that already has some of it is boring rather than a
-- transaction that aborts halfway and leaves you guessing what landed.
--
-- 0000_supabase_stubs.sql is deliberately NOT included: it recreates what
-- Supabase already provides and exists only so the test suite can run the
-- migrations against a bare Postgres.
`;

const rule = "-- ===================================================================";

const files = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(".sql") && !f.startsWith("0000_"))
  .sort();

const body = files
  .map((file) => {
    const sql = readFileSync(join(MIGRATIONS, file), "utf8").trimEnd();
    return `\n${rule}\n-- ${file}\n${rule}\n\n${sql}\n`;
  })
  .join("\n");

writeFileSync(OUT, `${HEADER}${body}`, "utf8");
console.log(`apply.sql ← ${files.length} migrations: ${files.join(", ")}`);
